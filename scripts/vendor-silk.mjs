// Regenerates server/channels/vendor/silk-package.ts from the installed
// silk-wasm package. Run `npm run vendor:silk` after upgrading silk-wasm.
//
// Paseo evaluates the plugin's server bundle without __filename/__dirname, so
// silk-wasm's own entry point (which locates its .wasm file relative to
// __filename) can't be bundled directly. Instead the package's bytes are
// embedded here and written to the plugin data directory at runtime, where a
// real require() gives them a proper module context again.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkgDir = join(root, "node_modules", "silk-wasm");
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;
const cjs = readFileSync(join(pkgDir, "lib", "index.cjs"), "utf8");
const wasmBase64 = readFileSync(join(pkgDir, "lib", "silk.wasm")).toString("base64");

const target = join(root, "server", "channels", "vendor", "silk-package.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/vendor-silk.mjs from silk-wasm@${version} — do not edit.

/** silk-wasm's package version, for the runtime extraction directory. */
export const SILK_VERSION = ${JSON.stringify(version)};

/** silk-wasm's CommonJS entry point, verbatim. */
export const SILK_CJS = ${JSON.stringify(cjs)};

/** silk-wasm's WebAssembly binary, base64. */
export const SILK_WASM_BASE64 = ${JSON.stringify(wasmBase64)};
`,
);
console.log(`wrote ${target} from silk-wasm@${version}`);
